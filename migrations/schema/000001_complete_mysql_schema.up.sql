CREATE TABLE product (
	pid VARCHAR(30) NOT NULL,
	pname VARCHAR(100) NULL DEFAULT NULL,
	ptype VARCHAR(20) NULL DEFAULT NULL,
	pinfo VARCHAR(350) NULL DEFAULT NULL,
	pprice DECIMAL(10,2) NOT NULL DEFAULT 0.00,
	pquantity INT NULL DEFAULT NULL,
	image LONGBLOB NULL DEFAULT NULL,
	PRIMARY KEY (pid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE `user` (
	email VARCHAR(100) NOT NULL,
	name VARCHAR(30) NULL DEFAULT NULL,
	mobile BIGINT NULL DEFAULT NULL,
	address VARCHAR(250) NULL DEFAULT NULL,
	pincode INT NULL DEFAULT NULL,
	password_hash VARCHAR(255) NULL DEFAULT NULL,
	must_reset_password BOOLEAN NOT NULL DEFAULT TRUE,
	PRIMARY KEY (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE orders (
	orderid VARCHAR(45) NOT NULL,
	prodid VARCHAR(45) NOT NULL,
	quantity INT NULL DEFAULT NULL,
	amount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
	shipped INT NOT NULL DEFAULT 0,
	PRIMARY KEY (orderid, prodid),
	KEY idx_orders_prodid (prodid),
	CONSTRAINT productid FOREIGN KEY (prodid) REFERENCES product (pid) ON DELETE NO ACTION ON UPDATE NO ACTION
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
