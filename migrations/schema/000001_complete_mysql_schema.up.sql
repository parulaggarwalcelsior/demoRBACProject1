CREATE TABLE product (
	pid VARCHAR(30) NOT NULL,
	pname VARCHAR(100) NULL DEFAULT NULL,
	ptype VARCHAR(20) NULL DEFAULT NULL,
	pinfo VARCHAR(350) NULL DEFAULT NULL,
	pprice DECIMAL(10,2) NOT NULL DEFAULT 0.00,
	pquantity INT NULL DEFAULT NULL,
	image LONGBLOB NULL DEFAULT NULL,
	PRIMARY KEY (pid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE `user` (
	email VARCHAR(100) NOT NULL,
	name VARCHAR(30) NULL DEFAULT NULL,
	mobile BIGINT NULL DEFAULT NULL,
	address VARCHAR(250) NULL DEFAULT NULL,
	pincode INT NULL DEFAULT NULL,
	password_hash VARCHAR(255) NULL DEFAULT NULL,
	must_reset_password BOOLEAN NOT NULL DEFAULT TRUE,
	PRIMARY KEY (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE orders (
	orderid VARCHAR(45) NOT NULL,
	prodid VARCHAR(45) NOT NULL,
	quantity INT NULL DEFAULT NULL,
	amount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
	shipped INT NOT NULL DEFAULT 0,
	PRIMARY KEY (orderid, prodid),
	CONSTRAINT productid FOREIGN KEY (prodid) REFERENCES product (pid) ON DELETE NO ACTION ON UPDATE NO ACTION
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE usercart (
	id BIGINT NOT NULL AUTO_INCREMENT,
	email VARCHAR(100) NOT NULL,
	pid VARCHAR(30) NOT NULL,
	quantity INT NOT NULL DEFAULT 1,
	added_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (id),
	UNIQUE KEY uq_usercart_email_pid (email, pid),
	CONSTRAINT ck_usercart_quantity CHECK (quantity >= 1),
	CONSTRAINT fk_usercart_email FOREIGN KEY (email) REFERENCES `user` (email) ON DELETE CASCADE ON UPDATE CASCADE,
	CONSTRAINT fk_usercart_pid FOREIGN KEY (pid) REFERENCES product (pid) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE user_demand (
	id BIGINT NOT NULL AUTO_INCREMENT,
	email VARCHAR(100) NOT NULL,
	book_name VARCHAR(100) NOT NULL,
	author VARCHAR(100) NULL,
	requested_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (id),
	CONSTRAINT fk_user_demand_email FOREIGN KEY (email) REFERENCES `user` (email) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE transactions (
	id BIGINT NOT NULL AUTO_INCREMENT,
	transaction_id VARCHAR(40) NOT NULL,
	email VARCHAR(100) NOT NULL,
	pid VARCHAR(30) NOT NULL,
	quantity INT NOT NULL,
	amount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
	created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (id),
	UNIQUE KEY uq_transactions_transaction_id (transaction_id),
	CONSTRAINT ck_transactions_quantity CHECK (quantity >= 1),
	CONSTRAINT fk_transactions_email FOREIGN KEY (email) REFERENCES `user` (email) ON DELETE RESTRICT ON UPDATE CASCADE,
	CONSTRAINT fk_transactions_pid FOREIGN KEY (pid) REFERENCES product (pid) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
